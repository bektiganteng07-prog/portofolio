create table if not exists public.proyek (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  stack text[] not null default '{}',
  href text not null,
  image_url text,
  image_alt text
);

alter table public.proyek enable row level security;

drop policy if exists "Public can read projects" on public.proyek;
drop policy if exists "Projects are readable by everyone" on public.proyek;
drop policy if exists "Authenticated can insert projects" on public.proyek;
drop policy if exists "Authenticated can update projects" on public.proyek;
drop policy if exists "Authenticated can delete projects" on public.proyek;

create policy "Projects are readable by everyone"
on public.proyek
for select
to anon, authenticated
using (true);

create policy "Authenticated can insert projects"
on public.proyek
for insert
to authenticated
with check (true);

create policy "Authenticated can update projects"
on public.proyek
for update
to authenticated
using (true)
with check (true);

create policy "Authenticated can delete projects"
on public.proyek
for delete
to authenticated
using (true);

grant select on table public.proyek to anon, authenticated;
grant insert, update, delete on table public.proyek to authenticated;
grant usage, select on sequence public.proyek_id_seq to authenticated;

insert into public.proyek (title, description, stack, href, image_url, image_alt)
select sample.title, sample.description, sample.stack, sample.href, sample.image_url, sample.image_alt
from (
  values
    (
      'KoperLine',
      'A digital design project with a clear visual concept and a practical user experience.',
      array['Figma']::text[],
      '/projects/koperline',
      null::text,
      null::text
    ),
    (
      'Web Gita Suradira',
      'A personal website designed to present information in a simple and engaging way.',
      array['HTML', 'CSS', 'JavaScript']::text[],
      '/projects/gita-suradira',
      null::text,
      null::text
    ),
    (
      'Personal Portfolio',
      'A personal portfolio website built to showcase projects, skills, and contact information.',
      array['Next.js', 'TypeScript', 'Supabase']::text[],
      '/projects/personal-portfolio',
      null::text,
      null::text
    )
) as sample(title, description, stack, href, image_url, image_alt)
where not exists (
  select 1
  from public.proyek as existing
  where existing.title = sample.title
);

update public.proyek
set href = '/projects/personal-portfolio'
where title = 'Personal Portfolio'
  and href <> '/projects/personal-portfolio';